        time_out = st.time_input("เวลาลงชื่อออก (เกณฑ์ปกติ 16.30 น.)", datetime.time(16, 30))
        task_done = st.text_area("ระบุชิ้นงาน/ภารกิจเชิงประจักษ์ที่ทำสำเร็จในวันนี้ (โปรดระบุให้ชัดเจน ห้ามใส่ว่าปฏิบัติงานปกติ)", placeholder="เช่น ซ่อมแซมระบบไฟฟ้าพัดลมห้อง ป.6 จำนวน 3 ตัว, ตรวจสอบคัตเอาท์อาคารเรียน")
