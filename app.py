    st.header("📝 บันทึกการปฏิบัติงานประจำวัน")
    st.info("💡 นโยบายสถานศึกษา: ไม่จำเป็นต้องมาก่อนเวลา 07.30 น. แต่ต้องปฏิบัติหน้าที่อย่างเต็มที่และเต็มเวลาในช่วงเวลา 08.30 น. - 16.30 น.")
    
    col1, col2 = st.columns(2)
    with col1:
        date_input = st.date_input("เลือกวันที่ปฏิบัติงาน", datetime.date.today())
        user_name = st.text_input("ชื่อ-นามสกุล ผู้ปฏิบัติงาน", placeholder="เช่น นายสิทธิพงษ์ แข็งขัน")
